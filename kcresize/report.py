def email_actioning(p, kind, detail="", link=""):
    """Work order / FYI / status for the actioning team."""
    last = (p.get("history") or [{}])[-1]
    if kind == "work_order":
        subject = f"[Kubecost] Work order: resize {p['id']} (approved by {last.get('actor', '?')})"
        lead = f"Approved by <b>{_h(last.get('actor', '?'))}</b>" + (f": &ldquo;{_h(last.get('detail'))}&rdquo;" if last.get("detail") else "")
        todo = "Comment <code>/apply</code> on the issue (environment-gated) or <code>/decline &lt;reason&gt;</code>."
    elif kind == "disapproved":
        subject = f"[Kubecost] No action needed: {p['id']} disapproved"
        lead = f"Disapproved by <b>{_h(last.get('actor', '?'))}</b>. Reason: &ldquo;{_h(last.get('detail', ''))}&rdquo;"
        todo = "Nothing to do."
    else:
        subject = f"[Kubecost] {p['id']}: {STATUS_TEXT.get(p['status'], p['status'])}"
        lead = _h(detail) or STATUS_TEXT.get(p["status"], p["status"])
        todo = ""
    rows = "".join(f"<li><code>{_h(c['container'])}</code> {_h(c['current']['cpu'])}/{_h(c['current']['memory'])} &rarr; <b>{_h(c['proposed']['cpu'])}/{_h(c['proposed']['memory'])}</b></li>" for c in p["containers"])
    body = f"""<div style="font-family:system-ui,Segoe UI,Arial,sans-serif;font-size:14px;color:#222;max-width:680px">
<h3 style="margin:0 0 6px">{_h(subject.replace('[Kubecost] ', ''))}</h3>
<p>{lead}</p><ul>{rows}</ul>
<p>Est. savings {money(p['monthlySavings'])}/mo · profile {_h(p['profile'])} · cluster {_h(p['cluster'])}{f" · Kubecost action <code>{_h(p['actionId'])}</code>" if p.get('actionId') else ''}</p>
{f'<p>{todo}</p>' if todo else ''}{f"<p><a href='{_h(link)}'>Open the issue</a></p>" if link else ''}</div>"""
    text = f"{subject}\n{html.unescape(lead).replace('<b>', '').replace('</b>', '')}\n" + \
           "\n".join(f"  {c['container']}: {c['current']['cpu']}/{c['current']['memory']} -> {c['proposed']['cpu']}/{c['proposed']['memory']}" for c in p["containers"]) + \
           (f"\n{link}" if link else "")
    return subject, body, text


# ---------- Slack (Block Kit)
def slack_owner_request(p, link="", interactive=False):
    a = p.get("allocation") or {}
    change = "\n".join(f"`{c['container']}` {c['current']['cpu']}/{c['current']['memory']} → *{c['proposed']['cpu']}/{c['proposed']['memory']}*" for c in p["containers"])
    blocks = [
        {"type": "header", "text": {"type": "plain_text", "text": "Kubecost resize approval needed"}},
        {"type": "section", "text": {"type": "mrkdwn", "text":
            f"*{p['id']}* ({p['env']}, profile {p['profile']}){'  :warning: large cut' if p.get('largeCut') else ''}\n"
            f"Now {money(a.get('monthlyCost'))}/mo · CPU {a.get('cpuUsageM', '?')}m used of {a.get('cpuRequestM', '?')}m · "
            f"RAM {a.get('ramUsageMi', '?')}Mi of {a.get('ramRequestMi', '?')}Mi · efficiency {a.get('efficiencyPct', '?')}%\n{change}\n"
            f"Saves ~{money(p['monthlySavings'])}/mo"}},
    ]
    val = f"{p['planId']}|{p['id']}"
    if interactive:   # handled by gateway/kcresize-gateway.py -> repository_dispatch
        blocks += [
            {"type": "input", "block_id": f"reason|{val}", "optional": True,
             "label": {"type": "plain_text", "text": "Reason (required to disapprove)"},
             "element": {"type": "plain_text_input", "action_id": "reason", "multiline": True, "max_length": 500}},
            {"type": "actions", "block_id": f"kc|{val}", "elements": [
                {"type": "button", "action_id": "kc_approve_force" if p.get("largeCut") else "kc_approve", "style": "primary",
                 "text": {"type": "plain_text", "text": "Approve (large cut)" if p.get("largeCut") else "Approve"}, "value": val},
                {"type": "button", "action_id": "kc_disapprove", "style": "danger", "text": {"type": "plain_text", "text": "Disapprove"}, "value": val}]}]
    elif link:
        blocks.append({"type": "actions", "elements": [{"type": "button", "text": {"type": "plain_text", "text": "Review and decide"}, "url": link, "style": "primary"}]})
    blocks.append({"type": "context", "elements": [{"type": "mrkdwn", "text": "Your decision is all that is needed; the platform team makes the change."}]})
    return {"text": f"Kubecost resize approval needed: {p['id']} (save ~{money(p['monthlySavings'])}/mo)", "blocks": blocks}


def slack_actioning(p, kind, detail="", link="", interactive=False):
    subject, _, text = email_actioning(p, kind, detail, link)
    blocks = [{"type": "section", "text": {"type": "mrkdwn", "text": "*" + subject.replace("[Kubecost] ", "") + "*\n" + "\n".join(text.splitlines()[1:])}}]
    val = f"{p['planId']}|{p['id']}"
    if kind == "work_order":
        if interactive:
            blocks.append({"type": "actions", "block_id": f"kcwo|{val}", "elements": [
                {"type": "button", "action_id": "kc_apply", "style": "primary", "text": {"type": "plain_text", "text": "Apply via Kubecost"}, "value": val},
                {"type": "button", "action_id": "kc_decline", "style": "danger", "text": {"type": "plain_text", "text": "Decline"}, "value": val}]})
        elif link:
            blocks.append({"type": "actions", "elements": [{"type": "button", "text": {"type": "plain_text", "text": "Open work order"}, "url": link}]})
    return {"text": subject, "blocks": blocks}


# ---------- Microsoft Teams (Workflows webhook + Adaptive Card)
def teams_card(title, facts, body_lines, actions=None, inputs=None):
    body = [{"type": "TextBlock", "text": title, "weight": "Bolder", "size": "Medium", "wrap": True},
            {"type": "FactSet", "facts": [{"title": k, "value": str(v)} for k, v in facts]}]
    body += [{"type": "TextBlock", "text": l, "wrap": True} for l in body_lines]
    body += inputs or []
    card = {"type": "AdaptiveCard", "version": "1.4", "msteams": {"width": "Full"}, "body": body}
    if actions:
        card["actions"] = actions
    return {"type": "message", "attachments": [{"contentType": "application/vnd.microsoft.card.adaptive", "content": card}]}


def teams_owner_request(p, link="", interactive=False):
    a = p.get("allocation") or {}
    facts = [("Workload", p["id"]), ("Env / profile", f"{p['env']} / {p['profile']}"), ("Cost now", f"{money(a.get('monthlyCost'))}/mo"),
             ("Efficiency", f"{a.get('efficiencyPct', '?')}%"), ("Est. savings", f"{money(p['monthlySavings'])}/mo")]
    lines = [f"{c['container']}: {c['current']['cpu']}/{c['current']['memory']} → **{c['proposed']['cpu']}/{c['proposed']['memory']}**" for c in p["containers"]]
    actions, inputs = [], []
    if interactive:   # "Post card and wait for a response" Workflow posts the result to the gateway
        inputs = [{"type": "Input.Text", "id": "reason", "isMultiline": True, "maxLength": 500, "placeholder": "Reason (required to disapprove)"}]
        actions = [{"type": "Action.Submit", "title": "Approve (large cut)" if p.get("largeCut") else "Approve", "style": "positive",
                    "data": {"event": "approve_force" if p.get("largeCut") else "approve", "workload": p["id"], "plan": p["planId"]}},
                   {"type": "Action.Submit", "title": "Disapprove", "style": "destructive",
                    "data": {"event": "disapprove", "workload": p["id"], "plan": p["planId"]}}]
    elif link:
        actions = [{"type": "Action.OpenUrl", "title": "Review and decide", "url": link}]
    return teams_card("Kubecost resize approval needed", facts, lines + ["Your decision is all that is needed; the platform team makes the change."], actions, inputs)


def teams_actioning(p, kind, detail="", link=""):
    subject, _, text = email_actioning(p, kind, detail, link)
    actions = [{"type": "Action.OpenUrl", "title": "Open", "url": link}] if link else None
    return teams_card(subject.replace("[Kubecost] ", ""), [("Workload", p["id"]), ("Est. savings", f"{money(p['monthlySavings'])}/mo")],
                      text.splitlines()[1:], actions)
