"""Render proposals for each audience and channel.

Owners get one thing: the approval request (cost evidence + proposed change + how to decide).
The actioning team gets everything after that: work orders, FYIs and status updates.
"""
import html

STATUS_TEXT = {
    "pending": "Waiting for the owner's decision",
    "approved": "Approved by the owner - waiting for the actioning team",
    "rejected": "Disapproved by the owner - no change",
    "scheduled": "Sent to Kubecost Actions - waiting for Kubecost to resize",
    "applied": "Resized by Kubecost",
    "failed": "Kubecost reported a failed resize",
    "declined": "Declined by the actioning team",
    "stale": "Out of date - re-plan needed",
    "expired": "Approval expired before it was actioned",
}


def money(v):
    return "n/a" if v is None else f"${v:,.2f}"


def _evidence(p):
    a = p.get("allocation") or {}
    if not a:
        return "Cost data: not available from the Allocation API for this window."
    hours = (a.get("dataMinutes") or 0) / 60
    return (f"Cost now **{money(a.get('monthlyCost'))}/mo** · CPU {a.get('cpuUsageM')}m used of {a.get('cpuRequestM')}m requested · "
            f"memory {a.get('ramUsageMi')}Mi of {a.get('ramRequestMi')}Mi · efficiency {a.get('efficiencyPct')}% "
            f"({hours:.0f}h of data)")


def _change_rows(p):
    return [f"| `{c['container']}` | {c['current']['cpu']} / {c['current']['memory']} | **{c['proposed']['cpu']} / {c['proposed']['memory']}** | "
            f"{(c.get('maxUsage') or {}).get('cpu', '?')} / {(c.get('maxUsage') or {}).get('memory', '?')} | {money(c['monthlySavings'])}/mo |"
            for c in p["containers"]]


def issue_markdown(p):
    """GitHub issue body: the owner's approval request, plus status and history."""
    owners = " ".join(f"@{u}" if not u.startswith("@") else u for u in p.get("owners", {}).get("github", []))
    lines = [
        f"## Resize approval: `{p['id']}`",
        "",
        f"**Status:** {STATUS_TEXT.get(p['status'], p['status'])}  ",
        f"**Cluster** `{p['cluster']}` · **env** {p['env']} · **profile** {p['profile']} · **plan** `{p['planId']}`" + (f" · **team** {p['team']}" if p.get("team") else ""),
        "",
        _evidence(p),
        "",
        "| Container | Current request | Proposed request | Peak usage | Est. savings |",
        "|---|---|---|---|---|",
        *_change_rows(p),
        "",
        f"**Estimated savings {money(p['monthlySavings'])}/mo**" + (f" (about {money(p.get('projectedMonthlyCost'))}/mo after)" if p.get("projectedMonthlyCost") is not None else ""),
    ]
    if p.get("blocked"):
        lines += ["", "> [!CAUTION]", "> Blocked by guardrails, cannot be approved: " + "; ".join(p["blocked"])]
    elif p["status"] == "pending":
        lines += ["", "### Owner decision" + (f" ({owners})" if owners else ""),
                  "Comment on this issue with one of:",
                  "",
                  "```",
                  "/approve " + ("--force " if p.get("largeCut") else "") + "<optional note>",
                  "/disapprove <reason, required>",
                  "```",
                  "That is all you need to do. The actioning team makes the change."]
        if p.get("largeCut"):
            lines += ["", "> [!WARNING]", "> This is a large cut for a production workload, so approving needs `--force`."]
    if p["status"] == "approved":
        lines += ["", "### Actioning team", "`/apply` (runs the Kubecost Action, gated by the `kubecost-actioning` environment) or `/decline <reason>`."]
    if p.get("actionId"):
        lines += ["", f"Kubecost action `{p['actionId']}` (`{p.get('actionName', '')}`)"]
    hist = p.get("history") or []
    if hist:
        lines += ["", "<details><summary>History</summary>", "", "| Time (UTC) | Event | By | Detail |", "|---|---|---|---|"]
        lines += [f"| {h['time']} | {h['event']} | {h.get('actor', '')} | {h.get('detail', '')} |" for h in hist]
        lines += ["", "</details>"]
    lines += ["", "<sub>Generated by kcresize from the Kubecost Allocation and Container Request Sizing APIs.</sub>"]
    return "\n".join(lines)


def plan_summary_markdown(plan_id, proposals, skipped, links=None):
    links = links or {}
    ok = [p for p in proposals if not p.get("blocked")]
    lines = [f"## Kubecost resize plan `{plan_id}`", "",
             f"**{len(ok)} proposal(s)**, est. savings **{money(sum(p['monthlySavings'] for p in ok))}/mo**"
             + (f", {len(proposals) - len(ok)} blocked" if len(ok) != len(proposals) else "") + ".", "",
             "| Workload | Env | Cost now | Efficiency | Proposed | Savings | Status |", "|---|---|---|---|---|---|---|"]
    for p in proposals:
        a = p.get("allocation") or {}
        prop = "<br>".join(f"{c['container']}: {c['proposed']['cpu']}/{c['proposed']['memory']}" for c in p["containers"])
        name = f"[{p['id']}]({links[p['id']]})" if links.get(p["id"]) else p["id"]
        st = "blocked" if p.get("blocked") else ("needs --force" if p.get("largeCut") else p["status"])
        lines.append(f"| {name} | {p['env']} | {money(a.get('monthlyCost'))}/mo | {a.get('efficiencyPct', '?')}% | {prop} | {money(p['monthlySavings'])}/mo | {st} |")
    if skipped:
        lines += ["", f"<sub>No significant change for: {', '.join(skipped[:20])}{' ...' if len(skipped) > 20 else ''}</sub>"]
    return "\n".join(lines)


# ---------- email (HTML + text)
def _h(s):
    return html.escape(str(s))


